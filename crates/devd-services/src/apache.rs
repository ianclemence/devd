//! Apache httpd configuration, rendered from the state store.
//!
//! The same inversion as [`crate::nginx`]: the database is the truth and
//! `httpd.conf` is output. Apache is here for the sites that depend on
//! `.htaccess` (`php_value`, authentication, rewrites that live beside the code),
//! which nginx cannot read.
//!
//! PHP is not loaded into Apache. Every PHP request is handed to the same
//! FastCGI listeners nginx uses (`mod_proxy_fcgi`), so one PHP installation, one
//! `php.ini` and one version per site serve both web servers, and Apache needs no
//! thread-safe PHP build or `LoadModule php_module` line.
//!
//! The installed Apache is either one devd downloaded (Apache Lounge's Windows
//! build, checked against the SHA-256 it publishes) or a directory a person
//! pointed devd at, such as the one a portable stack ships. The second is recorded in the
//! install manifest as `root`, and nothing in it is modified: devd writes its own
//! configuration under its own directory and passes it with `-f`.

use std::path::{Path, PathBuf};
use std::time::Duration;

use devd_core::capability::Ctx;
use devd_core::state::Site;
use devd_core::util;
use devd_core::{DevdError, Result};

/// The modules the generated configuration asks for, in load order. Each is
/// loaded only when its file exists, so an Apache built without one still starts
/// and `httpd -t` names what a site then lacks.
const MODULES: &[&str] = &[
    "authz_core",
    "authz_host",
    "alias",
    "dir",
    "env",
    "headers",
    "log_config",
    "mime",
    "rewrite",
    "setenvif",
    "socache_shmcb",
    "ssl",
    "proxy",
    "proxy_fcgi",
    "proxy_http",
    "proxy_wstunnel",
];

/// Everything the renderer needs that is not a site.
struct Render {
    /// Apache's ServerRoot, in slash form.
    root: String,
    /// devd's log directory, in slash form.
    logs: String,
    /// devd's certificate directory, in slash form.
    certs: String,
    /// Port the plain-HTTP listener uses.
    http: u16,
    /// Port the TLS listener uses.
    https: u16,
    /// The PHP FastCGI listeners, as series and port.
    php: Vec<(String, u16)>,
    /// The series the primary PHP version belongs to.
    primary: Option<String>,
    /// Modules whose files exist, so only those are loaded.
    modules: Vec<String>,
}

/// Where Apache's files are: the directory devd installed it in, or the one a
/// person adopted.
pub fn directory(ctx: &Ctx) -> PathBuf {
    adopted_root(ctx).unwrap_or_else(|| crate::install_dir(ctx, "apache").join("Apache24"))
}

/// The root recorded when an existing Apache was adopted.
fn adopted_root(ctx: &Ctx) -> Option<PathBuf> {
    crate::manifest_root(ctx, "apache")
}

/// The generated configuration file.
pub fn config_path(ctx: &Ctx) -> PathBuf {
    ctx.paths.etc().join("apache").join("httpd.conf")
}

/// The executable, relative to the Apache directory.
pub(crate) fn exe_name() -> &'static str {
    if cfg!(windows) {
        "bin/httpd.exe"
    } else {
        "bin/httpd"
    }
}

/// The `-d` argument: the server root as Apache reads it, with forward slashes.
pub(crate) fn root_arg(root: &Path) -> String {
    slashy(root)
}

fn slashy(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}

fn render_context(ctx: &Ctx) -> Render {
    let root = directory(ctx);
    let modules = MODULES
        .iter()
        .filter(|m| root.join("modules").join(format!("mod_{m}.so")).is_file())
        .map(|m| m.to_string())
        .collect();
    Render {
        root: slashy(&root),
        logs: slashy(&ctx.paths.logs()),
        certs: slashy(&ctx.paths.certs()),
        http: ctx.settings.http_port,
        https: ctx.settings.https_port,
        php: crate::nginx::php_listeners(ctx),
        primary: crate::primary_php_series(ctx),
        modules,
    }
}

/// Render `httpd.conf` from the state store and write it atomically.
pub fn render(ctx: &Ctx) -> Result<PathBuf> {
    let exe = directory(ctx).join(exe_name());
    if !exe.is_file() {
        return Err(DevdError::not_found(
            "Apache is not installed; run `devd service install apache`, or `devd service adopt apache --path <folder>` to use one you already have",
        ));
    }
    let sites = ctx.store.list_sites()?;
    let text = render_text(&render_context(ctx), &sites);
    let path = config_path(ctx);
    util::atomic_write(&path, &text)?;
    Ok(path)
}

/// The configuration text, as a pure function of its inputs.
fn render_text(render: &Render, sites: &[Site]) -> String {
    let mut out = String::with_capacity(2048 + sites.len() * 1500);
    out.push_str("# Generated by devd. Do not edit.\n");
    out.push_str("# The state store is the source of truth; this file is rewritten whenever a\n");
    out.push_str("# site or a setting changes. `devd web render` rewrites it, `devd web test`\n");
    out.push_str("# checks it with `httpd -t`, and `devd web reload` restarts Apache with it.\n\n");
    out.push_str(&format!("ServerRoot \"{}\"\n", render.root));
    out.push_str("ServerName localhost\n");
    out.push_str(&format!("PidFile \"{}/apache.pid\"\n", render.logs));
    out.push_str(&format!("Listen {}\n", render.http));
    if sites.iter().any(|s| s.tls_mode != "off") {
        out.push_str(&format!("Listen {}\n", render.https));
    }
    out.push('\n');
    for module in &render.modules {
        out.push_str(&format!("LoadModule {module}_module modules/mod_{module}.so\n"));
    }
    out.push('\n');
    out.push_str("ServerTokens Prod\nServerSignature Off\n");
    out.push_str("TimeOut 120\nKeepAlive On\nKeepAliveTimeout 65\n");
    out.push_str("EnableSendfile Off\n");
    out.push_str("LimitRequestBody 67108864\n");
    out.push_str(&format!("ErrorLog \"{}/apache-error.log\"\n", render.logs));
    out.push_str("LogLevel warn\n");
    out.push_str("<IfModule log_config_module>\n");
    out.push_str("    LogFormat \"%h %l %u %t \\\"%r\\\" %>s %b\" common\n");
    out.push_str(&format!("    CustomLog \"{}/apache-access.log\" common\n", render.logs));
    out.push_str("</IfModule>\n");
    out.push_str("<IfModule mime_module>\n");
    out.push_str("    TypesConfig conf/mime.types\n");
    out.push_str("</IfModule>\n");
    out.push_str("DirectoryIndex index.php index.html index.htm\n\n");
    // Nothing is served from a path no site named.
    out.push_str("<Directory />\n    AllowOverride None\n    Require all denied\n</Directory>\n\n");
    if render.modules.iter().any(|m| m == "ssl") && sites.iter().any(|s| s.tls_mode != "off") {
        out.push_str("SSLProtocol -all +TLSv1.2 +TLSv1.3\n");
        out.push_str("SSLSessionCache \"shmcb:logs/ssl_scache(512000)\"\n");
        out.push_str("SSLSessionCacheTimeout 300\n\n");
    }
    out.push_str(&default_server(render));
    for site in sites {
        out.push_str(&site_servers(render, site));
    }
    out
}

/// The listener name of the PHP series a site is sent to: pinned if installed,
/// else the primary, else the first. A site pinned to a version that is not
/// installed falls back, because a missing upstream is an error for every request.
fn site_php_port(render: &Render, site: &Site) -> u16 {
    let pinned = site.php.as_deref().map(crate::php_series).filter(|s| !s.is_empty());
    if let Some(series) = pinned {
        if let Some((_, port)) = render.php.iter().find(|(s, _)| s == &series) {
            return *port;
        }
    }
    if let Some(primary) = &render.primary {
        if let Some((_, port)) = render.php.iter().find(|(s, _)| s == primary) {
            return *port;
        }
    }
    render.php.first().map(|(_, p)| *p).unwrap_or(9000)
}

/// A request that matches no site says so rather than showing another project.
fn default_server(render: &Render) -> String {
    format!(
        "<VirtualHost *:{}>\n    ServerName devd-default.invalid\n    \
         ErrorDocument 404 \"No devd site is configured for this host. Run `devd site list` to see what is.\"\n    \
         <IfModule rewrite_module>\n        RewriteEngine On\n        RewriteRule ^ - [R=404,L]\n    </IfModule>\n</VirtualHost>\n\n",
        render.http
    )
}

/// The virtual hosts for one site.
fn site_servers(render: &Render, site: &Site) -> String {
    let root = slashy(Path::new(&site.document_root()));
    let host = &site.host;
    let tls = site.tls_mode != "off";
    let mut out = String::new();

    if tls {
        out.push_str(&format!(
            "<VirtualHost *:{}>\n    ServerName {host}\n    \
             Redirect permanent / https://{host}:{}/\n</VirtualHost>\n\n",
            render.http, render.https
        ));
    }

    let port = if tls { render.https } else { render.http };
    out.push_str(&format!("<VirtualHost *:{port}>\n    ServerName {host}\n"));
    if tls {
        let cert = format!("{}/{}", render.certs, host);
        out.push_str("    SSLEngine on\n");
        out.push_str(&format!("    SSLCertificateFile \"{cert}.crt\"\n"));
        out.push_str(&format!("    SSLCertificateKeyFile \"{cert}.key\"\n"));
    }
    out.push_str(&format!("    ErrorLog \"{}/apache-{host}.error.log\"\n", render.logs));
    out.push_str(&format!(
        "    CustomLog \"{}/apache-{host}.access.log\" common\n",
        render.logs
    ));

    if let Some(upstream) = &site.upstream {
        let target = upstream.trim_end_matches('/');
        out.push_str("    ProxyPreserveHost On\n    ProxyRequests Off\n");
        out.push_str(&format!(
            "    RequestHeader set X-Forwarded-Proto \"{}\"\n",
            if tls { "https" } else { "http" }
        ));
        // A dev server's hot-reload socket is an upgrade request; it goes to the
        // same program over ws://, everything else over http://.
        let ws = target.replacen("http://", "ws://", 1).replacen("https://", "wss://", 1);
        out.push_str("    RewriteEngine On\n");
        out.push_str("    RewriteCond %{HTTP:Upgrade} =websocket [NC]\n");
        out.push_str(&format!("    RewriteRule /(.*) {ws}/$1 [P,L]\n"));
        out.push_str(&format!("    ProxyPass / {target}/\n    ProxyPassReverse / {target}/\n"));
        out.push_str("    ProxyTimeout 3600\n");
        out.push_str("</VirtualHost>\n\n");
        return out;
    }

    out.push_str(&format!("    DocumentRoot \"{root}\"\n"));
    out.push_str(&format!("    <Directory \"{root}\">\n"));
    out.push_str("        Options FollowSymLinks\n");
    out.push_str("        AllowOverride All\n");
    out.push_str("        Require all granted\n");
    out.push_str("    </Directory>\n");
    // The script path goes into the URL explicitly. A `SetHandler proxy:fcgi://` handler
    // appends the file name to the address, and on Windows a name that starts with a
    // drive letter produces `:9000C:/...`, which Apache cannot parse.
    out.push_str(&format!(
        "    ProxyPassMatch \"^/(.*\\.php(/.*)?)$\" \"fcgi://127.0.0.1:{}/{root}/$1\"\n",
        site_php_port(render, site)
    ));
    // The same URL makes SCRIPT_FILENAME `/C:/...` on Windows, which php-cgi answers with
    // "No input file specified". The real path is the document root and the script name.
    out.push_str(&format!(
        "    ProxyFCGISetEnvIf \"true\" SCRIPT_FILENAME \"{root}%{{reqenv:SCRIPT_NAME}}\"\n"
    ));
    // `/index.php/extra`: the script is the part through `.php`, the rest is PATH_INFO. PATH_INFO
    // is set first and SCRIPT_NAME last, because each rule reads SCRIPT_NAME as it is when it runs.
    for (variable, value) in [("PATH_INFO", "$2".to_string()), ("SCRIPT_FILENAME", format!("{root}$1")), ("SCRIPT_NAME", "$1".to_string())] {
        out.push_str(&format!(
            "    ProxyFCGISetEnvIf \"reqenv('SCRIPT_NAME') =~ m#^(.+?\\.php)(/.*)$#\" {variable} \"{value}\"\n"
        ));
    }
    out.push_str("    # Dotfiles are not served; certificate challenges still are.\n");
    out.push_str("    <LocationMatch \"/\\.(?!well-known)\">\n        Require all denied\n    </LocationMatch>\n");
    out.push_str("</VirtualHost>\n\n");
    out
}

/// Run httpd against the generated configuration with extra arguments.
fn invoke(ctx: &Ctx, extra: &[&str]) -> Result<String> {
    let dir = directory(ctx);
    let exe = dir.join(exe_name());
    if !exe.is_file() {
        return Err(DevdError::not_found(
            "Apache is not installed; run `devd service install apache`",
        ));
    }
    let mut args = vec![
        "-d".to_string(),
        slashy(&dir),
        "-f".to_string(),
        slashy(&config_path(ctx)),
    ];
    args.extend(extra.iter().map(|s| s.to_string()));
    let out = util::run(&exe, &args, Some(&dir), &[], Some(Duration::from_secs(20)))?;
    Ok(format!("{}\n{}", out.stdout, out.stderr).trim().to_string())
}

/// `httpd -t`: parse the generated file and report what Apache says.
pub fn test(ctx: &Ctx) -> Result<String> {
    let output = invoke(ctx, &["-t"])?;
    if !output.contains("Syntax OK") {
        return Err(DevdError::Command {
            program: "httpd -t".to_string(),
            code: 1,
            stderr: util::truncate(output.trim(), 2000),
        });
    }
    Ok(output)
}

/// Version of an Apache directory, from `httpd -v`.
pub fn version(install: &Path) -> Option<String> {
    let exe = install.join(exe_name());
    if !exe.is_file() {
        return None;
    }
    let out = util::run(&exe, &["-v".to_string()], Some(install), &[], Some(Duration::from_secs(15))).ok()?;
    parse_version(&format!("{}\n{}", out.stdout, out.stderr))
}

/// `Server version: Apache/2.4.54 (Win64)` -> `2.4.54`.
fn parse_version(text: &str) -> Option<String> {
    let rest = text.split("Apache/").nth(1)?;
    let v: String = rest.chars().take_while(|c| c.is_ascii_digit() || *c == '.').collect();
    let v = v.trim_end_matches('.');
    (v.split('.').count() >= 2).then(|| v.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn site(name: &str, tls: &str, php: Option<&str>, upstream: Option<&str>) -> Site {
        Site {
            id: name.into(),
            name: name.into(),
            host: format!("{name}.test"),
            root: format!("C:\\www\\{name}"),
            web_server: "apache".into(),
            php: php.map(str::to_string),
            tls_mode: tls.into(),
            db_name: None,
            upstream: upstream.map(str::to_string),
            created_at: "2026-10-22T00:00:00Z".into(),
        }
    }

    fn render() -> Render {
        Render {
            root: "C:/stack/bin/apache/httpd-2.4.54-win64-VS16".into(),
            logs: "C:/devd/logs".into(),
            certs: "C:/devd/certs".into(),
            http: 8080,
            https: 8443,
            php: vec![("8.3".into(), 9083), ("8.5".into(), 9085)],
            primary: Some("8.5".into()),
            modules: vec!["rewrite".into(), "ssl".into(), "proxy".into(), "proxy_fcgi".into()],
        }
    }

    #[test]
    fn a_site_is_a_virtual_host_that_hands_php_to_its_own_listener() {
        let text = render_text(&render(), &[site("blog", "off", Some("8.3"), None), site("shop", "off", None, None)]);
        assert!(text.contains("ServerName blog.test"));
        assert!(text.contains("DocumentRoot \"C:/www/blog\""));
        // Pinned to 8.3, so that listener; the other follows the primary.
        assert!(text.contains("fcgi://127.0.0.1:9083/C:/www/blog/$1"), "{text}");
        assert!(text.contains("fcgi://127.0.0.1:9085/C:/www/shop/$1"));
        assert!(!text.contains("SetHandler"), "a drive letter breaks the SetHandler form on Windows");
        assert!(text.contains("ProxyFCGISetEnvIf \"true\" SCRIPT_FILENAME \"C:/www/blog%{reqenv:SCRIPT_NAME}\""));
        // The reason Apache is here.
        assert!(text.contains("AllowOverride All"));
        assert!(!text.contains("php_module"), "PHP is never loaded into Apache");
    }

    #[test]
    fn only_modules_that_exist_are_loaded_and_ports_follow_the_sites() {
        let plain = render_text(&render(), &[site("a", "off", None, None)]);
        assert!(plain.contains("LoadModule rewrite_module modules/mod_rewrite.so"));
        assert!(!plain.contains("proxy_http_module"), "a module with no file is not loaded");
        assert!(plain.contains("Listen 8080") && !plain.contains("Listen 8443"), "{plain}");
        let secure = render_text(&render(), &[site("a", "internal", None, None)]);
        assert!(secure.contains("Listen 8443"));
        assert!(secure.contains("SSLCertificateFile \"C:/devd/certs/a.test.crt\""));
        assert!(secure.contains("Redirect permanent / https://a.test:8443/"));
    }

    #[test]
    fn a_site_that_proxies_a_running_program_carries_websockets_through() {
        let text = render_text(&render(), &[site("app", "off", None, Some("http://127.0.0.1:5173"))]);
        assert!(text.contains("ProxyPass / http://127.0.0.1:5173/"));
        assert!(text.contains("RewriteRule /(.*) ws://127.0.0.1:5173/$1 [P,L]"));
        assert!(!text.contains("DocumentRoot \"C:/www/app\""), "a proxied site has no document root");
    }

    #[test]
    fn an_unknown_host_gets_a_404_not_another_project() {
        let text = render_text(&render(), &[site("a", "off", None, None)]);
        let default = text.find("devd-default.invalid").unwrap();
        let first_site = text.find("ServerName a.test").unwrap();
        assert!(default < first_site, "the first virtual host is Apache's default");
        assert!(text.contains("R=404"));
    }

    #[test]
    fn the_version_is_read_from_the_banner() {
        assert_eq!(parse_version("Server version: Apache/2.4.54 (Win64)\nServer built:   Jun  8 2022").as_deref(), Some("2.4.54"));
        assert_eq!(parse_version("nothing here"), None);
    }
}
