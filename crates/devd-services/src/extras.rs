//! Redis and Mailpit: the two services a PHP developer expects beside the web
//! server and the database.
//!
//! * **Redis** is supervised like the others. On Windows the only builds are
//!   third-party and publish no checksum, so devd does not download one: it
//!   adopts the folder a person already has. Elsewhere it
//!   adopts what the system's package manager installed, after checking it
//!   against the package.
//! * **Mailpit** catches the mail an application sends. It is downloaded from its
//!   GitHub release and checked against the SHA-256 GitHub records for the asset.
//!   PHP on Windows is pointed at it (`SMTP=127.0.0.1`, port 1025), so `mail()`
//!   lands in the inbox at `http://127.0.0.1:8025` instead of leaving the machine.

use std::path::{Path, PathBuf};
use std::time::Duration;

use devd_core::capability::Ctx;
use devd_core::util;
use devd_core::Result;

/// Where Mailpit takes mail from the applications.
pub const SMTP_PORT: u16 = 1025;
/// Where Mailpit's inbox is served.
pub const MAILPIT_UI_PORT: u16 = 8025;

// ------------------------------------------------------------------- Redis

/// The folder Redis runs from: the adopted one, or devd's install directory.
pub fn redis_directory(ctx: &Ctx) -> PathBuf {
    crate::manifest_root(ctx, "redis").unwrap_or_else(|| crate::install_dir(ctx, "redis"))
}

/// The Redis server, relative to its directory.
pub(crate) fn redis_exe_name() -> &'static str {
    if cfg!(windows) {
        "redis-server.exe"
    } else {
        "bin/redis-server"
    }
}

/// The Redis folder inside `folder`: the folder itself or a child that holds the server.
pub fn redis_root_of(folder: &Path) -> Option<PathBuf> {
    let exe = redis_exe_name();
    if folder.join(exe).is_file() {
        return Some(folder.to_path_buf());
    }
    let mut kids: Vec<PathBuf> = std::fs::read_dir(folder).ok()?.flatten().map(|e| e.path()).filter(|p| p.join(exe).is_file()).collect();
    kids.sort();
    kids.pop()
}

/// Where Redis keeps its snapshot.
pub fn redis_data_dir(ctx: &Ctx) -> PathBuf {
    ctx.paths.etc().join("redis").join("data")
}

/// The generated configuration.
pub fn redis_config_path(ctx: &Ctx) -> PathBuf {
    ctx.paths.etc().join("redis").join("redis.conf")
}

/// The configuration path as `redis-server` must be given it.
///
/// The Redis build devd downloads for Windows is an MSYS program. It reads a
/// path that starts with a drive letter as relative to the working directory
/// and then cannot find its own configuration, exiting with an empty log. It
/// accepts the same file as `/cygdrive/c/...`. A native build (an adopted
/// Memurai, say) wants the ordinary path, so only a folder that carries the
/// MSYS runtime is converted.
pub fn redis_config_arg(root: &Path, config: &Path) -> String {
    let plain = config.to_string_lossy().into_owned();
    if !cfg!(windows) || !root.join("msys-2.0.dll").is_file() {
        return plain;
    }
    cygdrive_path(&plain).unwrap_or(plain)
}

/// `C:\a\b` as `/cygdrive/c/a/b`, or `None` for a path without a drive letter.
fn cygdrive_path(path: &str) -> Option<String> {
    let mut chars = path.chars();
    let drive = chars.next().filter(char::is_ascii_alphabetic)?;
    let rest = chars.as_str().strip_prefix(':')?;
    let rest = rest.replace('\\', "/");
    Some(format!("/cygdrive/{}/{}", drive.to_ascii_lowercase(), rest.trim_start_matches('/')))
}

/// The text of `redis.conf`: loopback only, a snapshot on disk, logs to standard
/// output (which devd's supervisor writes to the service log).
pub fn redis_config_text(data_dir: &Path, port: u16) -> String {
    let data = data_dir.to_string_lossy().replace('\\', "/");
    format!(
        "# Generated by devd. Do not edit.\n\
         bind 127.0.0.1\n\
         port {port}\n\
         protected-mode yes\n\
         daemonize no\n\
         dir \"{data}\"\n\
         dbfilename dump.rdb\n\
         save 900 1\n\
         save 300 10\n\
         appendonly no\n\
         loglevel notice\n\
         logfile \"\"\n"
    )
}

/// Write `redis.conf` and the data directory.
pub fn redis_write_config(ctx: &Ctx, port: u16) -> Result<PathBuf> {
    std::fs::create_dir_all(redis_data_dir(ctx))?;
    let path = redis_config_path(ctx);
    util::atomic_write(&path, &redis_config_text(&redis_data_dir(ctx), port))?;
    Ok(path)
}

/// The version `redis-server --version` prints: `Redis server v=5.0.14.1 sha=...`.
pub fn redis_version(root: &Path) -> Option<String> {
    let exe = root.join(redis_exe_name());
    let out = util::run(&exe, &["--version".to_string()], Some(root), &[], Some(Duration::from_secs(15))).ok()?;
    util::extract_version(&format!("{}\n{}", out.stdout, out.stderr), Some(r"v=(\d+(?:\.\d+){1,3})"))
}

// ----------------------------------------------------------------- Mailpit

/// The Mailpit program, relative to its directory.
pub(crate) fn mailpit_exe_name() -> &'static str {
    if cfg!(windows) {
        "mailpit.exe"
    } else {
        "mailpit"
    }
}

/// Where Mailpit keeps what it caught.
pub fn mailpit_database(ctx: &Ctx) -> PathBuf {
    ctx.paths.etc().join("mailpit").join("mailpit.db")
}

/// Mailpit's argument array: SMTP and the inbox on loopback, mail kept on disk.
pub fn mailpit_args(ctx: &Ctx, ui_port: u16) -> Vec<String> {
    vec![
        "--smtp".to_string(),
        format!("127.0.0.1:{SMTP_PORT}"),
        "--listen".to_string(),
        format!("127.0.0.1:{ui_port}"),
        "--database".to_string(),
        mailpit_database(ctx).display().to_string(),
        "--disable-version-check".to_string(),
    ]
}

/// The lines that point PHP's `mail()` at Mailpit, between markers so they can be
/// replaced or removed without touching anything else in `php.ini`.
const MAIL_BEGIN: &str = "; ---- devd mail (managed by devd) ----";
const MAIL_END: &str = "; ---- end devd mail ----";

/// Add or replace the mail block of a `php.ini`. Returns whether the file changed.
pub fn php_ini_use_mailpit(ini: &Path, port: u16) -> Result<bool> {
    let text = std::fs::read_to_string(ini)?;
    let block = format!("{MAIL_BEGIN}\nSMTP = 127.0.0.1\nsmtp_port = {port}\nsendmail_from = \"devd@localhost\"\n{MAIL_END}\n");
    let updated = with_block(&text, Some(&block));
    if updated == text {
        return Ok(false);
    }
    util::atomic_write(ini, &updated)?;
    Ok(true)
}

/// Remove the mail block, leaving PHP's own defaults.
pub fn php_ini_forget_mailpit(ini: &Path) -> Result<bool> {
    let text = std::fs::read_to_string(ini)?;
    let updated = with_block(&text, None);
    if updated == text {
        return Ok(false);
    }
    util::atomic_write(ini, &updated)?;
    Ok(true)
}

fn with_block(text: &str, block: Option<&str>) -> String {
    let text = text.replace("\r\n", "\n");
    let mut out = match (text.find(MAIL_BEGIN), text.find(MAIL_END)) {
        (Some(a), Some(b)) if b > a => {
            let after = text[b + MAIL_END.len()..].trim_start_matches('\n');
            format!("{}{}", &text[..a], after)
        }
        _ => text.clone(),
    };
    if let Some(block) = block {
        if !out.ends_with('\n') {
            out.push('\n');
        }
        out.push_str(block);
    }
    out
}

/// Point every installed PHP at Mailpit (Windows only: elsewhere PHP sends mail
/// through `sendmail_path`, which devd does not rewrite).
pub fn point_php_at_mailpit(ctx: &Ctx) -> Result<Vec<String>> {
    let mut changed = Vec::new();
    if !cfg!(windows) {
        return Ok(changed);
    }
    for runtime in ctx.store.list_runtimes()? {
        if runtime.kind != "php" {
            continue;
        }
        let ini = Path::new(&runtime.path).join("php.ini");
        if ini.is_file() && php_ini_use_mailpit(&ini, SMTP_PORT)? {
            changed.push(runtime.version);
        }
    }
    Ok(changed)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn redis_listens_on_loopback_only_and_keeps_a_snapshot() {
        let text = redis_config_text(Path::new("C:\\devd\\etc\\redis\\data"), 6380);
        assert!(text.contains("bind 127.0.0.1") && text.contains("port 6380"));
        assert!(text.contains("dir \"C:/devd/etc/redis/data\""), "{text}");
        assert!(text.contains("protected-mode yes"));
    }

    #[test]
    fn a_drive_path_becomes_a_cygdrive_path_for_the_msys_redis() {
        assert_eq!(cygdrive_path("D:\\devd\\etc\\redis\\redis.conf").as_deref(), Some("/cygdrive/d/devd/etc/redis/redis.conf"));
        assert_eq!(cygdrive_path("C:/a/b").as_deref(), Some("/cygdrive/c/a/b"));
        assert_eq!(cygdrive_path("/etc/redis.conf"), None);
    }

    #[test]
    fn a_folder_without_the_msys_runtime_gets_the_ordinary_path() {
        let dir = std::env::temp_dir().join(format!("devd-redis-arg-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let conf = dir.join("redis.conf");
        assert_eq!(redis_config_arg(&dir, &conf), conf.to_string_lossy());
        #[cfg(windows)]
        {
            std::fs::write(dir.join("msys-2.0.dll"), b"").unwrap();
            assert!(redis_config_arg(&dir, &conf).starts_with("/cygdrive/"));
        }
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn the_mail_block_is_added_replaced_and_removed_without_touching_the_rest() {
        let original = "memory_limit = 512M\n[mail function]\n;SMTP = localhost\n";
        let with = with_block(original, Some(&format!("{MAIL_BEGIN}\nSMTP = 127.0.0.1\nsmtp_port = 1025\n{MAIL_END}\n")));
        assert!(with.starts_with(original) && with.contains("smtp_port = 1025"));
        let again = with_block(&with, Some(&format!("{MAIL_BEGIN}\nSMTP = 127.0.0.1\nsmtp_port = 2525\n{MAIL_END}\n")));
        assert_eq!(again.matches("devd mail (managed").count(), 1, "replaced, not duplicated: {again}");
        assert!(again.contains("smtp_port = 2525") && !again.contains("smtp_port = 1025"));
        let without = with_block(&again, None);
        assert_eq!(without, original);
    }

    #[test]
    fn php_ini_files_are_edited_in_place() {
        let dir = std::env::temp_dir().join(format!("devd-mail-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let ini = dir.join("php.ini");
        std::fs::write(&ini, "date.timezone = UTC\r\n").unwrap();
        assert!(php_ini_use_mailpit(&ini, 1025).unwrap());
        assert!(!php_ini_use_mailpit(&ini, 1025).unwrap(), "a second pass changes nothing");
        assert!(std::fs::read_to_string(&ini).unwrap().contains("SMTP = 127.0.0.1"));
        assert!(php_ini_forget_mailpit(&ini).unwrap());
        assert_eq!(std::fs::read_to_string(&ini).unwrap(), "date.timezone = UTC\n");
        let _ = std::fs::remove_dir_all(&dir);
    }
}
