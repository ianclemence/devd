# Cross-checks the docs against the code: every capability id a doc names in
# backticks must exist in the registry, and every relative link must resolve.
param([switch]$Verbose)

$ErrorActionPreference = "Stop"
$root = "D:\devd\www\devd"

# 1. Every capability-like id the code registers or dispatches.
#
# The shape in the source is `reg.define::<Args>("group.name", ...)` and
# `app.invoke("group.name", ...)`, so the closing quote is followed by a comma:
# requiring that keeps method calls and ordinary words out of the set.
$ids = @{}
Get-ChildItem (Join-Path $root "crates\devd-*\src\*.rs") | ForEach-Object {
    $text = [System.IO.File]::ReadAllText($_.FullName)
    foreach ($m in [regex]::Matches($text, '"([a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+)"\s*[,)]')) {
        $ids[$m.Groups[1].Value] = $true
    }
    foreach ($m in [regex]::Matches($text, 'define::<[^>]+>\("([a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+)"')) {
        $ids[$m.Groups[1].Value] = $true
    }
}
if ($Verbose) { Write-Output ("known capability ids: " + $ids.Count) }

# Families that exist without every member being listed ("git.*" tools).
function Looks-Like-Capability([string]$id) {
    return $ids.ContainsKey($id)
}

$badCaps = 0
foreach ($doc in Get-ChildItem (Join-Path $root "docs\*.md")) {
    $n = 0
    foreach ($line in [System.IO.File]::ReadAllLines($doc.FullName)) {
        $n++
        foreach ($m in [regex]::Matches($line, '`([a-z][a-z0-9_]*\.[a-z][a-z0-9_.]+)`')) {
            $id = $m.Groups[1].Value
            # A design note may name a capability it proposes. It is marked
            # `(planned)` on the line so a reader is never told it exists, and
            # so this check can tell a proposal from a claim.
            if ($line -match '\(planned\)') { continue }
            if ($id -match '\.(md|rs|js|toml|json|yml|yaml|txt|log|pid|db|sql|css|html|png|sh|ps1|bak|orig|rc|conf|ini|exe|com|test|app|dev|local)$') { continue }
            if (Looks-Like-Capability $id) { continue }
            # A dotted path inside a project, an env var, or a hostname is not an id.
            if ($id -match '^(www|src|bin|crates|docs|dist|target|certs|logs|services|runtimes|artifacts|snapshots|cache|workflows|roles|skills|templates|etc|state|home)\.') { continue }
            if ($id -match '^(d|h|x|s|p|c|i|l|v)\.') { continue }
            # Not every dotted word is a capability. These are schema keys, Git
            # configuration, column names, HTTP headers and file names, which is
            # why the check names the kinds it accepts rather than assuming.
            if ($id -match '^(project|process|health|restart|depends_on|working_dir|command|env|version)\.') { continue }        # devd.yml keys
            if ($id -match '^(core|user|http|credential|remote|branch|pull|push|receive|fetch|init|gc|diff|merge|rebase|advice|commit|tag|submodule|safe)\.') { continue }  # git config
            if ($id -match '^(team_runs|team_tasks|run_steps|runs|tools|chat|memory|review|intake|effects|suggestions|approvals|evidence|artifacts|run_events|observed|section|verified|init|policy|provider|model)\.') { continue } # column names
            # A php.ini directive, a code symbol, or a name a doc uses to say that
            # something does not exist is not a capability id.
            if ($id -match '^(opcache|date|display_errors|memory_limit|upload_max_filesize|post_max_size|max_execution_time|max_input_time)\.') { continue }
            if ($id -match '^(run_ctx|run_tasks|ctx)\.') { continue }
            if ($line -match '(-like effects|does not exist|there is no capability)') { continue }
            if ($id -match '\.(name|id|url|port|env|steps|timeout_secs|interval_ms)$') { continue }
            if ($id -match '^(index|page|app)\.') { continue }
            Write-Output ("{0}:{1}: `{2}` does not exist as a capability" -f $doc.Name, $n, $id)
            $badCaps++
        }
    }
}

# 2. Every `devd call <id>` names a real capability. This is the mistake a doc
#    makes most often: an id that reads well and does not exist, because the
#    capability was renamed or never built.
$files = @(Get-ChildItem (Join-Path $root "*.md")) + @(Get-ChildItem (Join-Path $root "docs\*.md"))
# A generated document is the output of a test, not prose. Rewriting it by hand -
# even to fix its punctuation - makes that test fail, so it is read but not checked.
$files = $files | Where-Object {
    $head = [System.IO.File]::ReadAllText($_.FullName)
    -not ($head -match '<!--\s*Generated from' -or $head -match 'generated by')
}
$badCalls = 0
foreach ($f in $files) {
    $n = 0
    foreach ($line in [System.IO.File]::ReadAllLines($f.FullName)) {
        $n++
        foreach ($m in [regex]::Matches($line, 'devd call ([a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+)')) {
            $id = $m.Groups[1].Value
            if (-not $ids.ContainsKey($id)) {
                Write-Output ("{0}:{1}: `devd call {2}` is not a capability" -f $f.Name, $n, $id)
                $badCalls++
            }
        }
    }
}

# 3. Every relative markdown link resolves.
$badLinks = 0
foreach ($f in $files) {
    $text = [System.IO.File]::ReadAllText($f.FullName)
    foreach ($m in [regex]::Matches($text, '\]\(([^)#\s]+\.md)(#[^)]*)?\)')) {
        $target = $m.Groups[1].Value
        if ($target -match '^https?:') { continue }
        $resolved = Join-Path $f.DirectoryName $target
        if (-not (Test-Path $resolved)) {
            Write-Output ("BROKEN LINK {0} -> {1}" -f $f.Name, $target)
            $badLinks++
        }
    }
}

Write-Output ("`ncapability ids named but missing: " + $badCaps)
Write-Output ("'devd call' naming a missing capability: " + $badCalls)
Write-Output ("broken relative links: " + $badLinks)
if (($badCaps + $badCalls + $badLinks) -gt 0) { exit 1 } else { exit 0 }
